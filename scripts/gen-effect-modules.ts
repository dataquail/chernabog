// Writes src/effect-modules.ts: every public `effect` entry point, so a flow or
// step loaded from a repo gets the binary's copy of each. Compiled binaries
// cannot resolve packages with wildcard `exports`, and `effect` has them.
// Run after changing the effect version: bun scripts/gen-effect-modules.ts

import { fileURLToPath } from 'node:url';

import { printJson } from '@chernabog/sdk';
import { BunRuntime, BunServices } from '@effect/platform-bun';
import * as Arr from 'effect/Array';
import * as Console from 'effect/Console';
import * as Effect from 'effect/Effect';
import * as FileSystem from 'effect/FileSystem';
import * as Option from 'effect/Option';
import * as Order from 'effect/Order';
import * as Schema from 'effect/Schema';

const root = fileURLToPath(new URL('../node_modules/effect/', import.meta.url));
const output = fileURLToPath(new URL('../src/effect-modules.ts', import.meta.url));

// A disabled export maps to null.
const Manifest = Schema.fromJsonString(Schema.Struct({ version: Schema.String, exports: Schema.Record(Schema.String, Schema.OptionFromNullOr(Schema.Json)) }));

const program = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const manifest = yield* Schema.decodeEffect(Manifest)(yield* fs.readFileString(`${root}package.json`));

  const named = Object.entries(manifest.exports)
    .filter(([key, target]) => key !== '.' && key !== './package.json' && !key.includes('*') && Option.isSome(target))
    .map(([key]) => `effect${key.slice(1)}`);

  // "./*" maps to every module in dist/, except internal/ and each directory's index.
  const wildcard = (yield* fs.readDirectory(`${root}dist`, { recursive: true }))
    .filter((file) => file.endsWith('.js') && !file.split('/').includes('internal') && !file.endsWith('index.js'))
    .map((file) => `effect/${file.slice(0, -3)}`);

  const specifiers = Arr.sort(Arr.dedupe([...named, ...wildcard]), Order.String);

  const lines = [
    `// Generated by scripts/gen-effect-modules.ts from effect@${manifest.version}. Do not edit.`,
    "// The barrel itself too: a flow's `import { Effect } from 'effect'` must get the binary's copy.",
    "import * as root from 'effect';",
    ...specifiers.map((specifier, index) => `import * as m${index} from '${specifier}';`),
    '',
    `export const EFFECT_VERSION = ${printJson(manifest.version)};`,
    '',
    'export const effectRoot = root;',
    '',
    'export const effectModules: Record<string, object> = {',
    ...specifiers.map((specifier, index) => `  '${specifier}': m${index},`),
    '};',
    '',
  ];

  yield* fs.writeFileString(output, lines.join('\n'));
  yield* Console.log(`${specifiers.length} effect entry points`);
});

BunRuntime.runMain(program.pipe(Effect.provide(BunServices.layer)));
